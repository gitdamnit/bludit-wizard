'use strict';
/*
 * Deterministic OpenAI-compatible mock provider for Bludit Wizard tests.
 *
 * The plugin calls `/chat/completions` and `/models` under the configured base
 * URL. This server answers both (any path ending in "models" or
 * "chat/completions") and records every request so tests can assert what the
 * plugin sent upstream.
 *
 * Control plane (test only):
 *   POST /__config  {content, status, delayMs, raw, models:{status, body, raw}}
 *   POST /__reset                                     -> restore defaults
 *   GET  /__state                                     -> {requests, config}
 */
const http = require('http');

const PORT = process.env.PORT ? Number(process.env.PORT) : 8090;

const DEFAULT_CONTENT = JSON.stringify({
  title: 'Mock Wizard Title',
  slug: 'mock-wizard-title',
  description: 'A deterministic description produced by the mock provider.',
  type: 'draft',
  content: '# Mock content\n\nBody generated by the mock provider.',
  tags: ['mock', 'wizard']
});

// OpenAI-style model list.
const OPENAI_MODELS = {
  object: 'list',
  data: [
    { id: 'gpt-4o-mini', object: 'model', owned_by: 'openai' },
    { id: 'gpt-4o', object: 'model', owned_by: 'openai' },
    { id: 'o3-mini', object: 'model', owned_by: 'openai' }
  ]
};

// OpenRouter-style list: names, pricing and tool support metadata.
const OPENROUTER_MODELS = {
  data: [
    {
      id: 'meta-llama/llama-3.1-8b-instruct:free',
      name: 'Llama 3.1 8B Instruct (free)',
      context_length: 131072,
      pricing: { prompt: '0', completion: '0' },
      supported_parameters: ['tools', 'temperature', 'max_tokens']
    },
    {
      id: 'openai/gpt-4o',
      name: 'GPT-4o',
      context_length: 128000,
      pricing: { prompt: '0.000005', completion: '0.000015' },
      supported_parameters: ['tools', 'temperature']
    },
    {
      id: 'mistralai/mistral-7b-instruct',
      name: 'Mistral 7B Instruct',
      context_length: 32768,
      pricing: { prompt: '0.0000002', completion: '0.0000006' }
    }
  ]
};

// LLM-Gateway-style list: names and cost metadata, no tool metadata.
const LLMGATEWAY_MODELS = {
  data: [
    { id: 'openai/gpt-5.4-mini', name: 'GPT-5.4 Mini', cost: { input: 0.15, output: 0.6 } },
    { id: 'anthropic/claude-sonnet-5', name: 'Claude Sonnet 5', cost: { input: 3, output: 15 } }
  ]
};

function defaultConfig() {
  return {
    content: DEFAULT_CONTENT,
    status: 200,
    delayMs: 0,
    raw: null,
    models: { status: 200, body: OPENAI_MODELS, raw: null }
  };
}

const CATALOGS = {
  openai: OPENAI_MODELS,
  openrouter: OPENROUTER_MODELS,
  llmgateway: LLMGATEWAY_MODELS
};

let state = { config: defaultConfig(), requests: [] };

function readBody(req) {
  return new Promise((resolve) => {
    let data = '';
    req.on('data', (c) => { data += c; });
    req.on('end', () => resolve(data));
  });
}

function json(res, status, obj) {
  const body = JSON.stringify(obj);
  res.writeHead(status, {
    'Content-Type': 'application/json',
    'Content-Length': Buffer.byteLength(body)
  });
  res.end(body);
}

const server = http.createServer(async (req, res) => {
  const url = req.url || '/';
  const body = await readBody(req);

  if (url === '/__reset') {
    state = { config: defaultConfig(), requests: [] };
    return json(res, 200, { ok: true });
  }
  if (url === '/__config') {
    let patch;
    try { patch = JSON.parse(body || '{}'); }
    catch (e) { return json(res, 400, { ok: false, error: 'bad config json' }); }
    for (const key of Object.keys(patch)) {
      if (key === 'models' && patch.models && typeof patch.models === 'object') {
        state.config.models = Object.assign({}, state.config.models, patch.models);
      } else if (key === 'catalog' && CATALOGS[patch.catalog]) {
        state.config.models = { status: 200, body: CATALOGS[patch.catalog], raw: null };
      } else {
        state.config[key] = patch[key];
      }
    }
    return json(res, 200, { ok: true, config: state.config });
  }
  if (url === '/__state') {
    return json(res, 200, { ok: true, count: state.requests.length, requests: state.requests, config: state.config });
  }

  // --- GET {base}/models -------------------------------------------------
  if (/\/models$/.test(url) && req.method === 'GET') {
    state.requests.push({ url, method: req.method, headers: req.headers, body: null, raw: '' });
    const mc = state.config.models || {};
    const status = Number(mc.status) || 200;
    if (status < 200 || status >= 300) {
      return json(res, status, { error: { message: 'Mock provider simulated models status ' + status, type: 'mock_error' } });
    }
    if (mc.raw !== null && mc.raw !== undefined) {
      res.writeHead(status, { 'Content-Type': 'application/json' });
      return res.end(String(mc.raw));
    }
    return json(res, status, mc.body === undefined ? OPENAI_MODELS : mc.body);
  }

  // --- POST {base}/chat/completions -------------------------------------
  if (url.endsWith('/chat/completions') && req.method === 'POST') {
    let parsed = null;
    try { parsed = JSON.parse(body); } catch (e) { /* keep null */ }
    state.requests.push({ url, method: req.method, headers: req.headers, body: parsed, raw: body });

    if (state.config.delayMs) {
      await new Promise((r) => setTimeout(r, state.config.delayMs));
    }
    const status = Number(state.config.status) || 200;
    if (status < 200 || status >= 300) {
      return json(res, status, { error: { message: 'Mock provider simulated status ' + status, type: 'mock_error' } });
    }
    if (state.config.raw !== null) {
      res.writeHead(status, { 'Content-Type': 'application/json' });
      return res.end(String(state.config.raw));
    }
    return json(res, status, {
      id: 'chatcmpl-mock',
      object: 'chat.completion',
      created: Math.floor(Date.now() / 1000),
      model: (parsed && parsed.model) || 'mock-model',
      choices: [
        { index: 0, message: { role: 'assistant', content: String(state.config.content) }, finish_reason: 'stop' }
      ],
      usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 }
    });
  }

  return json(res, 404, { ok: false, error: 'not found', url });
});

server.listen(PORT, '0.0.0.0', () => {
  console.log('mock-ai listening on ' + PORT);
});
